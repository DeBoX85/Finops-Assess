#!/usr/bin/env python3
"""Offline preparation for the first live (G2) session. Writes two generated documents:
  docs/UNVERIFIED-REGISTER.md  every UNVERIFIED / NOT SEEN / DON'T KNOW marker in the docs, with file and line
  docs/LIVE-TEST-SHEET.md      one row per check: collectors, permissions, confidence, and empty columns to fill in live
Usage: python scripts/live_readiness.py [--out-dir DIR]
Nothing here touches Azure. Re-run after docs or checks change; the files say so in their header."""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
MARK = re.compile(r"UNVERIFIED|NOT SEEN|DON'T KNOW", re.I)
SKIP = {"UNVERIFIED-REGISTER.md", "LIVE-TEST-SHEET.md", "MISTAKES.md"}
HEADER = "<!-- generated by scripts/live_readiness.py; do not edit by hand, re-run the script -->\n"


def register(root: pathlib.Path) -> tuple[str, int]:
    files = sorted(p for p in (root / "docs").rglob("*.md") if p.name not in SKIP and "mockups" not in p.parts and "log" not in p.parts)
    out, total = [], 0
    for p in files:
        hits = [(i, ln.strip()) for i, ln in enumerate(p.read_text().splitlines(), 1) if MARK.search(ln)]
        if not hits:
            continue
        total += len(hits)
        rel = p.relative_to(root).as_posix()
        out.append(f"## {rel} ({len(hits)})\n")
        out += [f"- line {i}: {t[:240]}{'...' if len(t) > 240 else ''}" for i, t in hits]
        out.append("")
    head = (
        f"{HEADER}# Register of unverified claims\n\n"
        f"{total} lines in {len([o for o in out if o.startswith('## ')])} files carry an UNVERIFIED, NOT SEEN or DON'T KNOW marker. "
        "A line can hold several claims and some lines only mention the word, so this is a worklist, not a count of open facts. "
        "Each claim is settled either by reading a Microsoft Learn page (doc item) or on a real tenant (live item). "
        "When one is settled, edit the source line to VERIFIED with the source and date, then re-run this script.\n"
    )
    return head + "\n" + "\n".join(out), total


def sheet() -> tuple[str, int]:
    from fcat import checks

    checks.load_builtin()
    rows = sorted(checks.REGISTRY, key=lambda x: x[0].id)
    lines = [
        f"{HEADER}# Live test sheet (gate G2)\n",
        f"{len(rows)} checks, all `offline-only` until a row below is filled in on a real tenant (hard rule 8). "
        "Columns on the right are for the live session: the OWNER creates canary resources, the tool never does. "
        "Verdict values: pass, false positive (describe), false negative (describe), query error, not assessed as designed.\n",
        "| Check | Title | Confidence | Collectors | Permissions | Canary created | Found | Known-good not flagged | Verdict | Date |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for m, _fn in rows:
        lines.append(f"| {m.id} | {m.title} | {m.confidence} | {', '.join(m.collectors)} | {', '.join(m.permissions)} |  |  |  |  |  |")
    return "\n".join(lines) + "\n", len(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=str(ROOT / "docs"))
    a = ap.parse_args(argv)
    out = pathlib.Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    reg, n = register(ROOT)
    sh, c = sheet()
    (out / "UNVERIFIED-REGISTER.md").write_text(reg)
    (out / "LIVE-TEST-SHEET.md").write_text(sh)
    print(f"register: {n} marker lines; live test sheet: {c} checks; written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
